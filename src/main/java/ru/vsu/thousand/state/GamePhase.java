package ru.vsu.thousand.state;

/**
 * Определяет последовательность фаз партии в игре «Тысяча».
 */
public enum GamePhase {

    /** Начало партии. */
    INITIALIZATION,

    /** Раздача карт игрокам. */
    DEALING,

    /** Торговля за прикуп. */
    BIDDING,

    /** Обмен картами с прикупом и снос лишних карт. */
    DISCARDING,

    /** Розыгрыш взяток. */
    PLAYING,

    /** Подсчёт очков за раунд. */
    SCORING,

    /** Завершение партии. */
    FINISHED
}